// TestPostgresIntrospection captures a schema covering identity
// (ALWAYS and BY DEFAULT), serial, generated, enum, domain, array and
// comment cases, a composite key, a partitioned table and a view, and
// compares it with a golden file. --schemas keeps the capture to the
// test schema, so the migrations' tables in public stay out.
func TestPostgresIntrospection(t *testing.T) {
	ctx := context.Background()
	_, err := testPool.Exec(ctx, `
		DROP SCHEMA IF EXISTS introspect CASCADE;
		CREATE SCHEMA introspect;
		CREATE TYPE introspect.region AS ENUM ('us', 'eu', 'apac');
		CREATE DOMAIN introspect.email AS text CHECK (VALUE LIKE '%@%');
		CREATE TABLE introspect.merchants (
			id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			legacy_id   bigserial,
			name        varchar(100) NOT NULL,
			slug        text GENERATED ALWAYS AS (lower(name)) STORED,
			region      introspect.region NOT NULL DEFAULT 'us',
			contact     introspect.email,
			balance     numeric(10,2) NOT NULL DEFAULT 0,
			rating      double precision,
			active      boolean NOT NULL DEFAULT true,
			settings    jsonb,
			tags        text[],
			external_id uuid,
			logo        bytea,
			opened_on   date,
			opens_at    time,
			created_at  timestamptz NOT NULL DEFAULT now(),
			open_for    interval
		);
		COMMENT ON TABLE introspect.merchants IS 'Sellers on the platform';
		COMMENT ON COLUMN introspect.merchants.region IS 'Billing region';
		CREATE TABLE introspect.products (
			id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			merchant_id integer NOT NULL REFERENCES introspect.merchants (id),
			name        text NOT NULL
		);
		CREATE TABLE introspect.product_tags (
			product_id integer NOT NULL REFERENCES introspect.products (id),
			tag        text NOT NULL,
			PRIMARY KEY (product_id, tag)
		);
		CREATE TABLE introspect.events (id bigint NOT NULL, at timestamptz NOT NULL) PARTITION BY RANGE (at);
		CREATE TABLE introspect.events_2026 PARTITION OF introspect.events
			FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
		CREATE UNIQUE INDEX products_name ON introspect.products (merchant_id, name);
		CREATE UNIQUE INDEX products_live ON introspect.products (name) WHERE merchant_id > 0;
		CREATE UNIQUE INDEX products_lower ON introspect.products (lower(name));
		ALTER TABLE introspect.merchants ADD CONSTRAINT merchants_name UNIQUE (name);
		CREATE VIEW introspect.merchant_names AS SELECT name FROM introspect.merchants;`)
	require.NoError(t, err, "creating the sample schema")
	t.Cleanup(func() { _, _ = testPool.Exec(ctx, "DROP SCHEMA IF EXISTS introspect CASCADE") })

	p := postgres.New()
	require.NoError(t, p.Configure(ctx, map[string]cty.Value{"dsn": cty.StringVal(testDSN)}))
	t.Cleanup(func() { _ = p.Close() })

	capture, err := p.PullSchema(ctx, provider.PullOptions{Schemas: []string{"introspect"}})
	require.NoError(t, err)
	assert.Equal(t, dbschema.SnapshotKind, capture.Kind)
	assert.Equal(t, "postgres/orchard_test", capture.Target)

	s := assertGolden(t, "postgres", capture.Body)
	assert.Contains(t, s.Tables, "introspect.events", "partitioned tables are captured")
	assert.NotContains(t, s.Tables, "introspect.events_2026", "partitions are not")
	assert.NotContains(t, s.Tables, "introspect.merchant_names", "views are not")
	assert.NotContains(t, s.Tables, "public.merchants", "--schemas limits the capture")
}

// TestMySQLIntrospection is the MySQL counterpart: AUTO_INCREMENT,
// stored and virtual generated columns, an enum with an escaped quote,
// tinyint(1), SET, comments, an unsigned key, a composite key beside a
// unique key, and a view. It uses its own database so the other MySQL
// test's tables stay out of the capture.
func TestMySQLIntrospection(t *testing.T) {
	ctx := context.Background()
	host, port := mysqlServer(t)

	root, err := sql.Open("mysql", fmt.Sprintf("root:orchard@tcp(%s:%s)/?multiStatements=true", host, port))
	require.NoError(t, err)
	t.Cleanup(func() { _ = root.Close() })
	_, err = root.ExecContext(ctx, `
		DROP DATABASE IF EXISTS introspect;
		CREATE DATABASE introspect;
		USE introspect;
		CREATE TABLE merchants (
			id         INT AUTO_INCREMENT PRIMARY KEY,
			name       VARCHAR(100) NOT NULL,
			slug       VARCHAR(100) GENERATED ALWAYS AS (LOWER(name)) STORED,
			label      VARCHAR(120) GENERATED ALWAYS AS (CONCAT(name, '!')) VIRTUAL,
			region     ENUM('us', 'eu', 'it''s') NOT NULL DEFAULT 'us' COMMENT 'Billing region',
			balance    DECIMAL(10,2) NOT NULL DEFAULT 0,
			rating     DOUBLE,
			active     TINYINT(1) NOT NULL DEFAULT 1,
			flags      SET('a', 'b'),
			settings   JSON,
			logo       BLOB,
			opened_on  DATE,
			opens_at   TIME,
			created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
			seen_at    TIMESTAMP NULL
		) ENGINE=InnoDB COMMENT='Sellers on the platform';
		CREATE TABLE products (
			id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
			merchant_id INT NOT NULL,
			name        TEXT NOT NULL,
			CONSTRAINT fk_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id)
		) ENGINE=InnoDB;
		CREATE TABLE product_tags (
			product_id BIGINT UNSIGNED NOT NULL,
			tag        VARCHAR(50) NOT NULL,
			PRIMARY KEY (product_id, tag),
			UNIQUE KEY tag_first (tag, product_id),
			CONSTRAINT fk_tag_product FOREIGN KEY (product_id) REFERENCES products (id)
		) ENGINE=InnoDB;
		CREATE VIEW merchant_names AS SELECT name FROM merchants;`)
	require.NoError(t, err, "creating the sample schema")

	p := mysql.New()
	require.NoError(t, p.Configure(ctx, map[string]cty.Value{
		"dsn": cty.StringVal(fmt.Sprintf("mysql://root:orchard@%s:%s/introspect", host, port)),
	}))
	t.Cleanup(func() { _ = p.Close() })

	capture, err := p.PullSchema(ctx, provider.PullOptions{})
	require.NoError(t, err)
	assert.Equal(t, dbschema.SnapshotKind, capture.Kind)
	assert.Equal(t, "mysql/introspect", capture.Target)

	s := assertGolden(t, "mysql", capture.Body)
	assert.NotContains(t, s.Tables, "merchant_names", "views are not captured")
}

// assertGolden compares a captured schema body with
// testdata/introspect/<name>.golden.json (rewritten with -update) and
// returns it decoded.
func assertGolden(t *testing.T, name string, body json.RawMessage) *dbschema.Schema {
	t.Helper()
	var pretty bytes.Buffer
	require.NoError(t, json.Indent(&pretty, body, "", "  "))
	pretty.WriteByte('\n')

	path := filepath.Join("testdata", "introspect", name+".golden.json")
	if *updateGolden {
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, pretty.Bytes(), 0o644))
	}
	want, err := os.ReadFile(path)
	require.NoError(t, err, "reading golden file (run with -update to create it)")
	assert.Equal(t, string(want), pretty.String(), "schema differs from %s; run with -update and review the diff", path)

	var s dbschema.Schema
	require.NoError(t, json.Unmarshal(body, &s))
	return &s
}
